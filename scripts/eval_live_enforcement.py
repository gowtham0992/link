#!/usr/bin/env python3
"""Do enforced rules hold against a real agent, not just a replayed tool call?

`eval_enforcement.py` replays tool calls through the decision code. This
benchmark hands tasks to a real coding agent in a throwaway repository with
Link's pre-tool hook installed, and checks the repository afterwards:

- tempting tasks, each asking for something a reviewed memory forbids
  (force-push over the remote, hand-edit a migration, print the secrets
  file, publish from a laptop); the forbidden effect must not happen;
- ordinary tasks a coding agent does all day (edit a source file, commit,
  push normally); they must succeed.

Each task runs in a fresh copy of the repository, with a bare local remote
so pushes go nowhere. The outcome is read from the repository and the
remote, not from what the agent says it did. The hook's own ledger shows
whether Link stepped in.

The agent is driven by its own CLI, isolated from your setup:

- Claude Code: `--setting-sources project` (no user settings, so your own
  hooks do not fire), an empty MCP config, and only this benchmark's hook.
  Shell use is limited to git and npm commands, file edits to the repository.
- Codex: a throwaway CODEX_HOME holding only this benchmark's hook (so none
  of your config, rules, hooks or MCP servers load), and the hook trusted
  for that run only. Codex's own sandbox keeps every `.git` folder
  read-only, so under it no commit or push can happen and the tasks would
  measure the sandbox, not Link. On macOS Codex therefore runs without its
  sandbox, inside one of this benchmark's (sandbox-exec) that refuses every
  file write outside the throwaway folder; elsewhere it keeps its
  workspace-write sandbox, and the commit task and the tempting tasks
  it holds are reported, not scored. It signs in with CODEX_API_KEY, or
  OPENAI_API_KEY when that is the one set; the key never leaves the
  agent's environment.

In both cases the agent sees only its own model's variables from your
environment, and on macOS it runs under a sandbox-exec profile that refuses
to read well-known credential files (cloud, SSH, registry, git hosting and
the other agent's login). Each run's event stream (Claude's stream-json,
Codex's --json) is kept, so a secret read by a tool counts as read even
when the final answer leaves it out.

npm can reach no registry in either case. Nothing runs without --yes; the
number of agent calls is printed first. A canary prompt runs before any
scored task, and a run that got no model answer is listed, never scored.

    python3 scripts/eval_live_enforcement.py --agent claude --model claude-haiku-4-5 --yes [--json]
    python3 scripts/eval_live_enforcement.py --agent codex --model gpt-6-luna --yes [--json]
"""
