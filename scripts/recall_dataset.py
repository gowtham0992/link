def _memory(name: str, domain: str, title: str, tldr: str, body: str, memory_type: str = "preference") -> dict[str, object]:
    return {
        "name": name,
        "title": title,
        "tldr": tldr,
        "tags": [domain],
        "body": body,
        "status": "active",
        "scope": "user",
        "memory_type": memory_type,
        "review_status": "reviewed",
        "domain": domain,
    }


# Deterministic phrasing wrappers applied to authored queries to grow the
# suite with surface variation (word order and framing changes only; they are
# counted separately from authored queries in reporting).
_WRAPPERS = [
    "{q}",
    "quick question: {q}",
    "remind me: {q}",
    "for this project, {q}",
]


def build_corpus() -> list[dict[str, object]]:
    memories = [
        _memory(name, domain, title, tldr, body)
        for name, domain, title, tldr, body, _queries in INTENTS
    ]
    memories.extend(
        _memory(name, domain, title, body[:80], body)
        for name, domain, title, body in _DISTRACTOR_TOPICS
    )
    return memories


def build_cases(expand: bool = True) -> list[dict[str, str]]:
    """Return benchmark cases: {query, target, domain, authored}."""
    cases: list[dict[str, str]] = []
    for name, domain, _title, _tldr, _body, queries in INTENTS:
        for query in queries:
            cases.append({"query": query, "target": name, "domain": domain, "authored": "yes"})
            if expand:
                for wrapper in _WRAPPERS[1:]:
                    cases.append({
                        "query": wrapper.format(q=query),
                        "target": name,
                        "domain": domain,
                        "authored": "wrapped",
                    })
    return cases
