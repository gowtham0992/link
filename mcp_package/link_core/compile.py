from .provenance import parse_anchor
from .security import injected_instruction_warnings, secret_value_warnings
from .staleness import repo_identity, safe_relative_path

BLOCK_BEGIN = "<!-- BEGIN LINK MEMORY: generated by `lnk compile` from reviewed Link memories; edit them in Link, not here -->"
BLOCK_END = "<!-- END LINK MEMORY -->"
OWNED_MARKER = "<!-- generated by `lnk compile` from Link memory; edit the memory in Link, not this file -->"
OWNED_PREFIX = "link-"

# Constraints first: they are what an agent most often gets wrong.
TYPE_PRIORITY = {"preference": 0, "decision": 1, "project": 2, "fact": 3, "note": 4}
ALWAYS_ON_TYPES = set(TYPE_PRIORITY)
SKILL_NAME_MAX = 64
SKILL_DESCRIPTION_MAX = 1024
DIRECTORY_GLOB_AT = 3  # anchors in this many files of one directory become dir/**


@dataclass(frozen=True)
class Target:
    """One agent file family: where it lives, its format and its budget."""

    key: str
    agent: str
    kind: str  # "block" (shared file), "rules" (one file per path-scoped memory), "always" (Link-owned always-on file), "skills"
    path: str  # file for block/always; directory for rules/skills
    budget_bytes: int | None = None
    budget_lines: int | None = None
    budget_chars: int | None = None
    budget_note: str = ""
    alternates: tuple[str, ...] = ()  # other accepted locations; an existing one is used instead
    # Paths whose presence shows the repository uses this agent. With no
    # --targets, compile writes AGENTS.md plus the agents already present,
    # instead of adding files for tools nobody here uses.
    signs: tuple[str, ...] = ()
    scoped_section: bool = False  # the agent has no path rules: list anchored memories in the block


# Budgets are the vendors' documented limits; where a vendor documents
# none, there is none here.
