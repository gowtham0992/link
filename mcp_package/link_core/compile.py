"""Compile reviewed memory into each coding agent's own instruction files.

Every agent reads instructions from files it already knows: AGENTS.md,
CLAUDE.md, GEMINI.md, Copilot's instruction files, Cursor, Windsurf and
Kiro rules, and Agent Skills. `lnk compile` renders the memories a person
has reviewed into those files, so they reach agents that have no MCP
connection or hooks, and keep reaching them if an agent drops its own
memory feature.

What is written, and how:

- Only reviewed, active memories. Unreviewed, archived, expired and
  quarantined (unreviewed team import) memories never are. Every memory is
  re-checked for secret-shaped values and injection-shaped instructions
  first; a flagged one is left out and reported.
- Only memories this repository should carry. Private memories are
  personal and stay out of files that get committed unless explicitly
  included. A memory fenced with `applies_when` is written only when its
  project or directory condition matches this repository; task conditions
  cannot be expressed in a static file, so those memories stay in recall.
- Always-on memories (preferences, decisions, facts, project context) go
  into one Link-owned block inside each shared file, between BEGIN/END
  markers. Everything outside the block is left byte for byte.
- Memories anchored to code (`path:line symbol @repo`) become path-scoped
  rule files in each agent's format, loaded when the agent works on those
  files. Procedure memories become Agent Skills.
- Link-owned files carry a generated-by marker. A file without it is
  never overwritten or removed; a stale Link-owned file is removed.
- Each target has a size budget. When the memories do not fit, the lowest
  priority ones (notes before facts before decisions and preferences,
  older before newer) are left out and reported - never silently cut.
- Output is deterministic: stable order, no timestamps. Compiling twice
  changes nothing, so `--check` can fail CI when the files drift from
  the store.
"""
from __future__ import annotations

import difflib
import fnmatch
import re
from collections.abc import Iterable, Mapping
from dataclasses import dataclass, field
from pathlib import Path

from .files import atomic_write_bytes
